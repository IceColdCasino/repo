export class UserInterface {
  sit(seat: number) {
    const seatsGroup = document.querySelector('g#seats');
    const seatPosition = seatPositions[seat];
    const gImgs = document.createElementNS('http://www.w3.org/2000/svg', 'g');
    gImgs.innerHTML = `
      <circle cx="${seatPosition.x}" cy="${seatPosition.y}" r="32" />
      <image class="player${seat}" x="${seatPosition.x}" y="${seatPosition.y}" width="6000" height="6000" href="https://raw.githubusercontent.com/larvalabs/cryptopunks/refs/heads/master/punks.png" />
    `;
    seatsGroup.appendChild(gImgs);
    const q = document.querySelector(`#seats image.player${seat}`) as SVGImageElement;
    const rand = Math.floor(Math.random() * smokers.length);
    q.style.setProperty('--n', smokers[rand].toString());
  }

  dealPlayerCardsFaceDown(seats: number[]) {
    const playerCards = document.querySelector('g#player_cards');
    for (const seat of seats) {
      const cardPosition = cardPositions[seat];
      const gPlayerCards = document.createElementNS('http://www.w3.org/2000/svg', 'g');
      gPlayerCards.id = `player${seat}_cards`;
      gPlayerCards.innerHTML = `
        <g>
          <rect x="${cardPosition.x}" y="${cardPosition.y}" width="58" height="78" />
          <text x="${cardPosition.x - 6}" y="${cardPosition.y + 66}">&#x1F0A0;</text>
        </g>
        <g>
          <rect x="${cardPosition.x + 70}" y="${cardPosition.y}" width="58" height="78" />
          <text x="${cardPosition.x + 64}" y="${cardPosition.y + 66}">&#x1F0A0;</text>
        </g>
      `;
      playerCards.appendChild(gPlayerCards);
    }
  }

  dealSharedCardsFaceDown() {
    for (let p = 0; p < sharedCardPositons.length; p++) {
      const sc = sharedCardPositons[p];
      const sharedCards = document.querySelector('#shared_cards');
      const g = document.createElementNS('http://www.w3.org/2000/svg', 'g');
      g.id = sc.id;
      g.innerHTML = `
        <rect x="${sc.x}" y="${sc.y}" width="96" height="128" rx="4" />
        <text x="${sc.x - 8}" y="${sc.y + 106}">&#x1F0A0;</text>
      `;
      sharedCards.appendChild(g);
    }
  }
}
