const MARKER_BEGIN = '# BEGIN light-protocol genesis (do not hand-edit; regenerated by light-localnet)';
const MARKER_END = '# END light-protocol genesis';

/**
 * Append Light [[test.genesis]] + [[test.validator.account]] blocks to poker Anchor.toml.
 * Must run after `arcium localnet` regenerates the file and before the validator
 * process is spawned — or before a clean restart that re-reads Anchor.toml.
 *
 * Returns false if Light CLI accounts/bins are missing.
 */
export function injectLightGenesisIntoAnchorToml(
  anchorTomlPath: string = path.join(process.cwd(), 'rust/casino/Anchor.toml'),
): { ok: boolean; reason?: string; accountCount?: number; programCount?: number } {
  if (!fs.existsSync(LIGHT_ACCOUNTS_DIR)) {
    return { ok: false, reason: `Missing Light accounts dir: ${LIGHT_ACCOUNTS_DIR}` };
  }
  const resolvedPrograms: { id: string; soPath: string }[] = [];
  for (const prog of LIGHT_SYSTEM_PROGRAMS) {
    const soPath = resolveLightProgramSo(prog.so);
    if (!soPath) {
      return { ok: false, reason: `Missing Light program binary: ${prog.so} (checked artifacts/light and CLI bin)` };
    }
    resolvedPrograms.push({ id: prog.id, soPath });
  }

  if (!fs.existsSync(anchorTomlPath)) {
    return { ok: false, reason: `Missing Anchor.toml: ${anchorTomlPath}` };
  }

  let text = fs.readFileSync(anchorTomlPath, 'utf8');
  // Strip previous injection
  const begin = text.indexOf(MARKER_BEGIN);
  const end = text.indexOf(MARKER_END);
  if (begin !== -1 && end !== -1 && end > begin) {
    text = text.slice(0, begin) + text.slice(end + MARKER_END.length);
    text = text.replace(/\n{3,}/g, '\n\n');
  }

  const accountFiles = fs
    .readdirSync(LIGHT_ACCOUNTS_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort();

  const lines: string[] = ['', MARKER_BEGIN];
  for (const prog of resolvedPrograms) {
    lines.push('[[test.genesis]] # light-protocol');
    lines.push(`address = "${prog.id}"`);
    lines.push(`program = "${prog.soPath}"`);
    lines.push('upgradeable = false');
  }
  const seenAddresses = new Set<string>();
  for (const file of accountFiles) {
    const full = path.join(LIGHT_ACCOUNTS_DIR, file);
    let address: string | undefined;
    try {
      const j = JSON.parse(fs.readFileSync(full, 'utf8')) as { pubkey?: string };
      address = j.pubkey;
    } catch {
      /* skip bad file */
    }
    if (!address || seenAddresses.has(address)) continue;
    seenAddresses.add(address);
    lines.push('[[test.validator.account]] # light-protocol');
    lines.push(`address = "${address}"`);
    lines.push(`filename = "${full}"`);
  }
  lines.push(MARKER_END, '');

  fs.writeFileSync(anchorTomlPath, text.trimEnd() + '\n' + lines.join('\n') + '\n');
  return {
    ok: true,
    accountCount: seenAddresses.size,
    programCount: resolvedPrograms.length,
  };
}

/** True when Anchor.toml currently contains the Light genesis marker block. */
export function anchorTomlHasLightGenesis(
  anchorTomlPath: string = path.join(process.cwd(), 'rust/casino/Anchor.toml'),
): boolean {
  if (!fs.existsSync(anchorTomlPath)) return false;
  const text = fs.readFileSync(anchorTomlPath, 'utf8');
  return text.includes(MARKER_BEGIN) && text.includes(LIGHT_SYSTEM_PROGRAM_ID);
}

/**
 * Keep validator RPC on a concrete host IP (Agave rejects 0.0.0.0).
 * Prefer en0 / SOLANA_BIND_ADDRESS so Apple Container ARX can reach RPC.
 * `arcium localnet` may rewrite Anchor.toml; re-apply before the validator spawns.
 */
function detectHostLanIp(): string {
  if (process.env.SOLANA_BIND_ADDRESS) return process.env.SOLANA_BIND_ADDRESS;
  try {
    const r = spawnSync('ipconfig', ['getifaddr', 'en0'], { encoding: 'utf8' });
    const ip = (r.stdout ?? '').trim();
    if (/^\d+\.\d+\.\d+\.\d+$/.test(ip)) return ip;
  } catch {
    /* ignore */
  }
  return '127.0.0.1';
}

export function pinValidatorBindAddress(
  anchorTomlPath: string = path.join(process.cwd(), 'rust/casino/Anchor.toml'),
  bindAddress = detectHostLanIp(),
): boolean {
  if (!fs.existsSync(anchorTomlPath)) return false;
  const text = fs.readFileSync(anchorTomlPath, 'utf8');
  if (/bind_address\s*=\s*"[^"]*"/.test(text)) {
    const next = text.replace(
      /bind_address\s*=\s*"[^"]*"/,
      `bind_address = "${bindAddress}"`,
    );
    if (next === text) return false;
    fs.writeFileSync(anchorTomlPath, next);
    return true;
  }
  // Insert under [test.validator] if present, else create the section.
  if (text.includes('[test.validator]')) {
    const next = text.replace(
      /\[test\.validator\]/,
      `[test.validator]\nbind_address = "${bindAddress}"`,
    );
    fs.writeFileSync(anchorTomlPath, next);
    return true;
  }
  fs.writeFileSync(
    anchorTomlPath,
    `${text.trimEnd()}\n\n[test.validator]\nbind_address = "${bindAddress}"\n`,
  );
  return true;
}

export type LightSidecarHandles = {
  photon?: ChildProcess;
  prover?: ChildProcess;
  keysHttp?: ChildProcess;
};

/** Local HTTP port that serves proving-keys/ (CHECKSUM) when GCS returns 403. */
export const LIGHT_KEYS_HTTP_PORT = Number(process.env.LIGHT_KEYS_HTTP_PORT ?? 39291);

/**
 * Public CloudFront distribution that replaced
 * `storage.googleapis.com/light-protocol-proving-keys` (that bucket 404s).
 * The prover binary still defaults to the old URL.
 */
const LIGHT_PROVING_KEYS_URL = process.env.LIGHT_PROVING_KEYS_URL
  ?? 'https://d1wbn9ra8wjh7t.cloudfront.net';

/** Ensure keys-dir/CHECKSUM exists so the prover can verify offline via local download-url. */
export function ensureLocalProvingKeyChecksum(keysDir: string): string {
  const checksumPath = path.join(keysDir, 'CHECKSUM');
  const keyFiles = fs.readdirSync(keysDir).filter((f) => f.endsWith('.key')).sort();
  if (keyFiles.length === 0) {
    throw new Error(`No .key files in ${keysDir}`);
  }
  // Always refresh from on-disk keys — GCS CHECKSUM is often 403 now.
  const lines: string[] = [];
  for (const file of keyFiles) {
    const buf = fs.readFileSync(path.join(keysDir, file));
    const hash = createHash('sha256').update(buf).digest('hex');
    lines.push(`${hash}  ${file}`);
  }
  fs.writeFileSync(checksumPath, `${lines.join('\n')}\n`);
  return checksumPath;
}

/**
 * Start Photon + Light prover against an already-running RPC (e.g. Arcium localnet).
 * Does NOT start a validator and does NOT load Light genesis accounts.
 *
 * Prover key loading: GCS CHECKSUM downloads currently 403, so we serve
 * `.light-home/.../proving-keys` on localhost and pass `--download-url` there.
 */
export function startLightSidecars(options: {
  rpcUrl?: string;
  indexerPort?: number;
  proverPort?: number;
  logDir?: string;
} = {}): LightSidecarHandles {
  const rpcUrl = options.rpcUrl ?? lightRpcUrl();
  const indexerPort = options.indexerPort ?? 8784;
  const proverPort = options.proverPort ?? 3001;
  const logDir = options.logDir
    ?? path.join(process.cwd(), 'rust/casino');
  fs.mkdirSync(logDir, { recursive: true });

  // Avoid duplicate sidecars
  stopLightSidecars();

  const handles: LightSidecarHandles = {};

  const photonBin = spawnSync('which', ['photon'], { encoding: 'utf8' }).stdout?.trim();
  if (photonBin) {
    const currentSlot = spawnSync(
      'solana',
      ['slot', '--url', rpcUrl],
      { encoding: 'utf8' },
    ).stdout?.trim();
    const startSlotArgs = currentSlot && /^\d+$/.test(currentSlot)
      ? ['--start-slot', currentSlot]
      : [];
    const photonLog = fs.openSync(path.join(logDir, '.photon.log'), 'w');
    handles.photon = spawn(
      photonBin,
      [
        '--rpc-url', rpcUrl,
        '--port', String(indexerPort),
        '--prover-url', `http://127.0.0.1:${proverPort}`,
        ...startSlotArgs,
      ],
      { stdio: ['ignore', photonLog, photonLog], detached: true },
    );
    handles.photon.unref();
  }

  // Prefer downloaded prover binary (light CLI `start-prover` shells out to `ps`).
  const proverBinaryCandidates = [
    path.join(process.env.HOME ?? '', '.config/light/bin/prover-darwin-arm64'),
    path.join(process.cwd(), '.light-home/.config/light/bin/prover-darwin-arm64'),
    path.join(process.env.HOME ?? '', '.config/light/bin/prover-linux-amd64'),
  ];
  const keysDirCandidates = [
    path.join(process.env.HOME ?? '', '.config/light/proving-keys'),
    path.join(process.cwd(), '.light-home/.config/light/proving-keys'),
  ];
  const proverBin = proverBinaryCandidates.find((p) => fs.existsSync(p));
  const keysDir = keysDirCandidates.find((p) => fs.existsSync(p))
    ?? path.join(process.env.HOME ?? '', '.config/light/proving-keys');
  if (proverBin) {
    fs.mkdirSync(keysDir, { recursive: true });
    const proverLog = fs.openSync(path.join(logDir, '.light-prover.log'), 'w');
    handles.prover = spawn(
      proverBin,
      [
        'start',
        '--keys-dir', `${keysDir}/`,
        '--prover-address', `0.0.0.0:${proverPort}`,
        '--auto-download',
        '--download-url', LIGHT_PROVING_KEYS_URL,
        '--preload-keys', 'none',
      ],
      { stdio: ['ignore', proverLog, proverLog], detached: true },
    );
    handles.prover.unref();
  } else {
    const lightBin = spawnSync('which', ['light'], { encoding: 'utf8' }).stdout?.trim();
    if (lightBin) {
      const proverLog = fs.openSync(path.join(logDir, '.light-prover.log'), 'w');
      handles.prover = spawn(
        lightBin,
        ['start-prover', '--prover-port', String(proverPort)],
        { stdio: ['ignore', proverLog, proverLog], detached: true },
      );
      handles.prover.unref();
    }
  }

  return handles;
}

export function stopLightSidecars(): void {
  spawnSync('pkill', ['-f', 'photon --rpc-url'], { stdio: 'pipe' });
  spawnSync('pkill', ['-f', 'light start-prover'], { stdio: 'pipe' });
  // light-prover binary name used by CLI
  spawnSync('pkill', ['-f', 'light-prover'], { stdio: 'pipe' });
  spawnSync('pkill', ['-f', 'prover-darwin-arm64'], { stdio: 'pipe' });
  spawnSync('pkill', ['-f', 'prover-linux-amd64'], { stdio: 'pipe' });
  spawnSync(
    'pkill',
    ['-f', `python3 -m http.server ${LIGHT_KEYS_HTTP_PORT}`],
    { stdio: 'pipe' },
  );
}
