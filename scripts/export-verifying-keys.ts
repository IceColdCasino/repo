/**
 * Turn snarkjs verification keys into groth16-solana byte arrays.
 *
 * G1 is big-endian x || y. G2 is big-endian x.c1 || x.c0 || y.c1 || y.c0.
 *
 *   bun scripts/export-verifying-keys.ts slot_showdown_3_reel_hashout_main
 *   bun scripts/export-verifying-keys.ts --check register_main
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'fs';
import { join } from 'path';

const ROOT = join(import.meta.dir, '..');
const ZKEY_DIR = join(ROOT, 'zkey');
const VK_ROOT = join(
  ROOT,
  'rust/light-casino/programs/light-casino/src/verifying_keys',
);

type G1 = [string, string, string];
type Fp2 = [string, string];
type G2 = [Fp2, Fp2, Fp2];

type VkJson = {
  nPublic: number;
  vk_alpha_1: G1;
  vk_beta_2: G2;
  vk_gamma_2: G2;
  vk_delta_2: G2;
  IC: G1[];
};

function beBytes(value: string, width: number): number[] {
  let v = BigInt(value);
  const out = new Array<number>(width);
  for (let i = width - 1; i >= 0; i--) {
    out[i] = Number(v & 255n);
    v >>= 8n;
  }
  if (v !== 0n) throw new Error(`field element does not fit in ${width} bytes: ${value}`);
  return out;
}

function g1(point: G1): number[] {
  return [...beBytes(point[0], 32), ...beBytes(point[1], 32)];
}

function g2(point: G2): number[] {
  const [x, y] = point;
  return [
    ...beBytes(x[1], 32),
    ...beBytes(x[0], 32),
    ...beBytes(y[1], 32),
    ...beBytes(y[0], 32),
  ];
}

function fmtBytes(bytes: number[], indent: string): string {
  const lines: string[] = [];
  for (let i = 0; i < bytes.length; i += 16) {
    const cells = bytes.slice(i, i + 16).map((b) => String(b).padStart(3)).join(', ');
    lines.push(`${indent}${cells},`);
  }
  return lines.join('\n');
}

function render(name: string, vk: VkJson): string {
  const ic = vk.IC.map((point) => `    [\n${fmtBytes(g1(point), '    ')}\n    ],`).join('\n');
  return `// Auto-generated from ${name}_verification_key.json
// nPublic = ${vk.nPublic}
// Generated by scripts/export-verifying-keys.ts — do not edit by hand.

use groth16_solana::groth16::Groth16Verifyingkey;

pub const NR_PUBINPUTS: usize = ${vk.nPublic};

pub const VK_ALPHA_G1: [u8; 64] = [
${fmtBytes(g1(vk.vk_alpha_1), '    ')}
];

pub const VK_BETA_G2: [u8; 128] = [
${fmtBytes(g2(vk.vk_beta_2), '    ')}
];

pub const VK_GAMMA_G2: [u8; 128] = [
${fmtBytes(g2(vk.vk_gamma_2), '    ')}
];

pub const VK_DELTA_G2: [u8; 128] = [
${fmtBytes(g2(vk.vk_delta_2), '    ')}
];

pub const VK_IC: &[[u8; 64]] = &[
${ic}
];

pub const VERIFYING_KEY: Groth16Verifyingkey = Groth16Verifyingkey {
    nr_pubinputs: NR_PUBINPUTS,
    vk_alpha_g1: VK_ALPHA_G1,
    vk_beta_g2: VK_BETA_G2,
    vk_gamme_g2: VK_GAMMA_G2,
    vk_delta_g2: VK_DELTA_G2,
    vk_ic: VK_IC,
};
`;
}

function findRustFile(name: string): string | null {
  const target = `${name}.rs`;
  const walk = (dir: string): string | null => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) {
        const found = walk(path);
        if (found) return found;
      } else if (entry === target) {
        return path;
      }
    }
    return null;
  };
  return walk(VK_ROOT);
}

const args = process.argv.slice(2);
const check = args[0] === '--check';
const names = check ? args.slice(1) : args;
if (names.length === 0) {
  console.error('usage: bun scripts/export-verifying-keys.ts [--check] <circuit>...');
  process.exit(1);
}

let failed = false;
for (const name of names) {
  const jsonPath = join(ZKEY_DIR, `${name}_verification_key.json`);
  const vk = JSON.parse(readFileSync(jsonPath, 'utf8')) as VkJson;
  if (vk.IC.length !== vk.nPublic + 1) {
    throw new Error(`${name}: IC length ${vk.IC.length} != nPublic + 1 (${vk.nPublic + 1})`);
  }
  const rendered = render(name, vk);
  const rustPath = findRustFile(name);
  if (!rustPath) {
    console.error(`no rust verifying key for ${name}`);
    failed = true;
    continue;
  }
  if (check) {
    const current = readFileSync(rustPath, 'utf8');
    if (current !== rendered) {
      console.error(`mismatch ${rustPath}`);
      failed = true;
    } else {
      console.log(`match ${name}`);
    }
  } else {
    writeFileSync(rustPath, rendered);
    console.log(`wrote ${rustPath}`);
  }
}

if (failed) process.exit(1);
