/**
 * Public subset-sum weights for the showdown coefficient seal.
 *
 * weight[k][n] = SHA-256(DOMAIN || k || n as u16 BE) >> 14, so every weight is
 * below 2^242 and a row sum over the two live coefficients stays below 2^253.
 * Each row is then the same integer in BN254 and in Arcis BaseField25519.
 *
 * Writes the Circom, Zig, and Arcis tables:
 *   bun scripts/gen-seal-weights.ts
 */
import { createHash } from 'crypto';
import { writeFileSync } from 'fs';
import { join } from 'path';

const ROWS = 4;
const SLOTS = 2;
const BITS = 128;
const WIDTH = SLOTS * BITS;
const WEIGHT_BITS = 242;
const DOMAIN = 'IceColdCasino showdown seal weights v1';
const ROOT = join(import.meta.dir, '..');
const HEADER = 'Generated by scripts/gen-seal-weights.ts. Do not edit.';

function weight(row: number, index: number): bigint {
  const tag = Buffer.alloc(3);
  tag.writeUInt8(row, 0);
  tag.writeUInt16BE(index, 1);
  const digest = createHash('sha256').update(DOMAIN).update(tag).digest();
  return BigInt(`0x${digest.toString('hex')}`) >> BigInt(256 - WEIGHT_BITS);
}

const weights = Array.from({ length: ROWS }, (_, k) =>
  Array.from({ length: WIDTH }, (_, n) => weight(k, n)),
);

const rowMax = weights.map((row) => row.reduce((a, b) => a + b, 0n));
const BN254 = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const ED25519 = (1n << 255n) - 19n;
for (const max of rowMax) {
  if (max >= BN254 || max >= ED25519) throw new Error('row sum can wrap a field');
}

function chunk<T>(items: T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

function hex64(value: bigint): string {
  return `0x${value.toString(16).padStart(16, '0')}`;
}

function limbs(value: bigint): string {
  const mask = (1n << 64n) - 1n;
  return [0n, 64n, 128n, 192n].map((shift) => hex64((value >> shift) & mask)).join(', ');
}

const circomSlot = (i: number) => {
  const rows = weights.map((row) => {
    const lines = chunk(row.slice(i * BITS, (i + 1) * BITS), 3).map((group) => `        ${group.join(', ')}`);
    return `      [\n${lines.join(',\n')}\n      ]`;
  });
  return `    return [\n${rows.join(',\n')}\n    ];`;
};
const circomBranches = Array.from({ length: SLOTS }, (_, i) => {
  const body = circomSlot(i);
  if (i === 0) return `  if (i == 0) {\n${body}\n  }`;
  if (i === SLOTS - 1) return ` else {\n    assert(i == ${i});\n${body}\n  }`;
  return ` else if (i == ${i}) {\n${body}\n  }`;
}).join('');
const circom = `/*
Copyright 2026 by Barrett Harber. All rights reserved.

Patent Pending USPTO Application Number 19/811,546
*/

pragma circom 2.2.2;

// ${HEADER}
// sealSlotWeights(i)[k][j] weighs bit j of sealed coefficient i in row k.
// One slot per call keeps the witness stack frame at 512 weights; the
// parallel witness thread has a 512 KB stack.
function sealSlotWeights(i) {
${circomBranches}
}
`;
writeFileSync(join(ROOT, 'circuits/seal_weights.circom'), circom);

const zigRows = weights.map((row) => {
  const lines = row.map((value) => `        .{ ${limbs(value)} },`);
  return `    .{\n${lines.join('\n')}\n    },`;
});
const zig = `//! ${HEADER}
//! SEAL_WEIGHTS[k][i * 128 + j] weighs bit j of sealed coefficient i in row k.
//! Little-endian u64 limbs, normal (non-Montgomery) form, each below 2^${WEIGHT_BITS}.
pub const Limb4 = [4]u64;
pub const ROWS = ${ROWS};
pub const WIDTH = ${WIDTH};
pub const SEAL_WEIGHTS = [ROWS][WIDTH]Limb4{
${zigRows.join('\n')}
};
`;
writeFileSync(join(ROOT, 'libzkcasino/src/zig/crypto/seal_weights.zig'), zig);

const mask128 = (1n << 128n) - 1n;
const flat = weights.flat();
const rustTable = (name: string, values: bigint[]) => {
  const lines = chunk(values, 4).map((group) => `    ${group.join(', ')},`);
  return `const ${name}: [u128; ${values.length}] = [\n${lines.join('\n')}\n];`;
};
const rust = `// ${HEADER}
// Weight of bit j of sealed coefficient i in row k, at n = k * ${WIDTH} + i * 128 + j:
// SEAL_WEIGHTS_LO[n] + SEAL_WEIGHTS_HI[n] * 2^128.
${rustTable('SEAL_WEIGHTS_LO', flat.map((value) => value & mask128))}

${rustTable('SEAL_WEIGHTS_HI', flat.map((value) => value >> 128n))}
`;
writeFileSync(join(ROOT, 'rust/casino/encrypted-ixs/src/seal_weights.rs'), rust);

console.log(`rows ${ROWS} x ${WIDTH}; max row sum < 2^${rowMax.map((m) => m.toString(2).length).reduce((a, b) => Math.max(a, b))}`);
